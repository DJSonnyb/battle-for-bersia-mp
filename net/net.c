/* per frame from the title scene */
/* ---- menu navigation order: next/prev focus walks the parent's child vector (+0x24c begin, +0x250 end,
   focused index +0x258) in creation order. Controls added by code (or created out of visual order) land
   out of order, so re-sort each kind of control (same vtable) by screen position, top-to-bottom then
   left-to-right, keeping the slots each kind already occupies. Index 0 is left alone. */
volatile i32 nav_done;
static void nav_sort(void *panel)
{
    if (!panel) return;
    void **b = *(void***)((char*)panel + 0x24c), **e = *(void***)((char*)panel + 0x250);
    if (!b || e <= b) return;
    int n = (int)(e - b); if (n > 128) return;
    int fi = *(i32*)((char*)panel + 0x258);
    void *foc = (fi >= 0 && fi < n) ? b[fi] : 0;
    int idx[128]; char done[128];
    for (int i = 0; i < n; i++) done[i] = 0;
    for (int i = 1; i < n; i++) {
        if (done[i] || !b[i]) continue;
        void *vt = *(void**)b[i]; int m = 0;
        for (int j = i; j < n; j++) if (!done[j] && b[j] && *(void**)b[j] == vt) { idx[m++] = j; done[j] = 1; }
        if (m < 2) continue;
        void *c[128];
        for (int k = 0; k < m; k++) c[k] = b[idx[k]];
        for (int k = 1; k < m; k++) {               /* stable insertion sort by (y, x) */
            void *v = c[k]; float vy = *(float*)((char*)v + 0x30), vx = *(float*)((char*)v + 0x2c);
            int j = k - 1;
            while (j >= 0) {
                float y = *(float*)((char*)c[j] + 0x30), x = *(float*)((char*)c[j] + 0x2c);
                if (y > vy + 2.0f || (y > vy - 2.0f && x > vx)) { c[j+1] = c[j]; j--; } else break;
            }
            c[j+1] = v;
        }
        for (int k = 0; k < m; k++) b[idx[k]] = c[k];
    }
    if (foc) for (int i = 0; i < n; i++) if (b[i] == foc) { *(i32*)((char*)panel + 0x258) = i; break; }
}
static void nav_all(void)
{
    char *t = nav_title;
    void *multi = *(void**)(t + 0x384);
    if (multi) nav_sort(*(void**)((char*)multi + 0x14));      /* title main menu */
    nav_sort(*(void**)(t + 0x388));                            /* lobby */
    nav_sort(*(void**)0xAE1DF0);                               /* multiplayer menu */
    nav_sort(gl_ctrl[0]);                                      /* game list */
    nav_sort(*(void**)0xAE1D44);                               /* army select buttons */
    nav_sort(*(void**)0xAE1D48);                               /* host / join */
    nav_sort(*(void**)0xAE1DB8);                               /* create game */
}

void net_update(void)
{
    skill_fix();
    if (nav_title && !nav_done) { nav_done = 1; nav_all(); }
    if (!ctx) return;
    if (call_kind) {
        char f = 0;
        if (ut_done(h_call, &f)) {
            int k = call_kind; call_kind = 0;
            if (k == 513) on_created(); else if (k == 510) on_list(); else if (k == 504) on_enter();
            net_dirty = 1;
        }
    }
    if (lobby && netw()) {
        int n0 = mm_num_members(lobby);
        for (int i = 0; i < n0 && i < 8; i++) p2p_accept(mm_member(lobby, i));
        u32 sz; int guard = 32;
        while (guard-- && p2p_avail(&sz) && sz) {
            static unsigned char *buf; u32 got = 0; u64 from = 0;     /* v88: 4 KB on the heap (bss must end below Keaton's fixes) */
            if (!buf) buf = (unsigned char *)((void *(*)(u32))0x8D5E88)(4096);
            if (!buf || sz > 4096) break;
            if (!p2p_read(buf, 4096, &got, &from) || got < 4) continue;
            if (buf[0]=='K' && buf[1]=='P' && got >= 8) { buf[1] = 'Q'; p2p_send(from, buf, 8, 0); continue; }
            if (buf[0]=='K' && buf[1]=='M') { md_host_req(from, buf, got); continue; }   /* TEST38 custom map download */
            if (buf[0]=='K' && buf[1]=='F') { md_recv(from, buf, got); continue; }
            if (buf[0]=='K' && (buf[1]=='T' || buf[1]=='A' || buf[1]=='L')) { ls_handle(buf, got, from); continue; }
            if (buf[0]=='K' && buf[1]=='C' && got >= 3) { buf[got < 4096 ? got : 4095] = 0; buf[101] = 0;
                for (u32 q = 2; buf[q]; q++) if (buf[q] < 0x20 || buf[q] > 0x7e || buf[q] == '@') buf[q] = '?';
                chat_add((const char*)buf + 2); continue; }
            if (buf[0]=='K' && buf[1]=='Q' && got >= 8) {
                u32 rtt = now_ms() - *(u32*)(buf+4);
                for (int k = 0; k < 8; k++) if (ping_id[k] == from || !ping_id[k]) { ping_id[k] = from; ping_ms[k] = rtt > 9999 ? 9999 : (i32)rtt; break; }
                continue;
            }
            if (buf[0]=='K' && buf[1]=='S' && !net_is_host && from == mm_owner(lobby) && got >= 16 + 8*6) {
                /* START: 'K','S',map,mode, nplayers(u32), seed(u32), pad, ids[6] */
                want_mode = buf[3] <= 2 ? buf[3] : 0; want_map = buf[2] >= 27 && buf[2] < 100 ? (cm_join >= 27 ? cm_join : 0) : valid_map(buf[2], want_mode); want_resp = buf[12] & 3;   /* TEST37 custom map: our own index */ want_dmg = (buf[12] >> 4) & 7; if (want_dmg > (want_mode == 1 ? 5 : 4)) want_dmg = 0;   /* TEST38: 5 = Roguelike hero start */ net_delay = (buf[13] >= 5 && buf[13] <= 15) ? buf[13] : 5;
                net_nplayers = *(u32*)(buf+4); net_seed = *(u32*)(buf+8); coop_sup = buf[14] <= 4 ? buf[14] : 0;   /* v95 host's co-op support choice */
                u64 me = my_id(); net_local_slot = -1;
                for (int k = 0; k < 6; k++) { net_slot_ids[k] = *(u64*)(buf+16+8*k); if (net_slot_ids[k] == me) net_local_slot = k; }
                net_spec = net_local_slot >= (i32)net_nplayers;   /* v96 */
                if (got >= 76) for (int k = 0; k < 6; k++) { net_slot_team[k] = buf[64+k]; net_slot_col[k] = buf[70+k]; }
                net_go = 1;
            }
        }
    }
    if (friend_ticks > 0) { friend_ticks--; if (net_state == 4 && (friend_ticks % 20) == 0) net_dirty = 1; }
    if (lobby) {
        int n = mm_num_members(lobby);
        if (n != last_members) { last_members = n; net_dirty = 1; }
        if ((net_state == 2 || net_state == 6) && (++last_tick % 30) == 0) {
            net_dirty = 1;   /* member names/heroes/pings arrive later */
            unsigned char pk[8] = { 'K','P',0,0 }; *(u32*)(pk+4) = now_ms();
            u64 me = my_id();
            for (int i = 0; i < n && i < 8; i++) { u64 id = mm_member(lobby, i); if (id && id != me) p2p_send(id, pk, 8, 0); }
        }
        if (!net_is_host && net_state == 6 && (last_tick % 30) == 1) cm_tick();
        if (net_is_host) md_host_tick();
        else md_join_tick();
        if (!net_is_host && net_state == 6) {
            /* host left -> lobby closes for us */
            u64 o = mm_owner(lobby);
            if (n <= 1 && o) { }
        }
    }
}

