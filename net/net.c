void net_host(int maxp, int map, int mode)
{
    if (!ensure()) { net_state = 7; return; }
    if (lobby) net_leave();
    want_max = maxp < 2 ? 2 : (maxp > 6 ? 6 : maxp); want_map = map; want_mode = mode;
    net_is_host = 1; net_state = 1;
    want_resp = net_resp & 3; cur_pub = net_pub ? 1 : 0; want_dmg = (u32)net_dmg <= 4 ? net_dmg : 0;
    begin_call(mm_create(cur_pub ? 1 /*friends only*/ : 2 /*public*/, lobby_cap()), 513);
    if (!call_kind) net_state = 7;
    net_dirty = 1;
}

