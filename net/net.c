static void on_list(void)
{
    u32 cnt = 0; char f = 0;
    if (!ut_result(h_call, &cnt, 4, 510, &f) || f) { net_state = 7; return; }
    for (int i = 0; i < (int)cnt && n_list < 6; i++) {
        u64 id = mm_lobby_by_index(i); int dup = 0;
        for (int k = 0; k < n_list; k++) if (list_ids[k] == id) dup = 1;
        if (!dup) { list_band[n_list] = search_band; list_ids[n_list++] = id; }
    }
    if (search_band < 3 && n_list < 6) { search_band++; search_next(); return; }
    n_public = n_list;
    /* friends' games (private matches are friends-only and never appear in the public list) */
    u32 app = ut_appid();
    int nf = fr_count(4 /* immediate */);
    for (int i = 0; i < nf && n_list < 6; i++) {
        fgi_t g; memset(&g, 0, sizeof g);
        u64 f = fr_by_index(i, 4);
        if (!f || !fr_game(f, &g) || !g.lobby) continue;
        if (app && (u32)(g.game & 0xFFFFFF) != app) continue;
        int dup = 0; for (int k = 0; k < n_list; k++) if (list_ids[k] == g.lobby) dup = 1;
        if (dup) continue;
        mm_request_data(g.lobby);
        list_ids[n_list++] = g.lobby;
    }
    if (n_list > n_public) friend_ticks = 120;   /* refresh rows while friend lobby data arrives */
    net_state = 4;
}

