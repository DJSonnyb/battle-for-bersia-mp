/* The game font only has Latin glyphs: keep printable ASCII; names with none (e.g. Japanese) become "Player N". */
static void clean_name(char *out, const char *in, int n)
{
    int k = 0, alnum = 0;
    if (in) for (int i = 0; in[i] && k < 31; i++) {
        unsigned char c = (unsigned char)in[i];
        if (c >= 0x20 && c < 0x7f) { out[k++] = (char)c; if ((c|32) >= 'a' && (c|32) <= 'z') alnum = 1; if (c >= '0' && c <= '9') alnum = 1; }
    }
    while (k > 0 && out[k-1] == ' ') k--;
    out[k] = 0;
    if (!alnum) SPRINTF(out, "Player %d", n);
}
