static void ls_poll(void)
{
    if (!netw()) return;
    u32 sz; int guard = 64;
    if (!ls_heap) return;
    unsigned char *buf = ls_heap + 0x3000;       /* v80: 4 KB receive buffer on the heap (.kuf bss is full) */
    while (guard-- && p2p_avail(&sz) && sz) {
        u32 got = 0; u64 from = 0;
        if (sz > 0x1000) { p2p_read(buf, 0x1000, &got, &from); continue; }
        if (!p2p_read(buf, 0x1000, &got, &from) || got < 4) continue;
        if (buf[0] == 'K' && (buf[1] == 'T' || buf[1] == 'A' || buf[1] == 'L')) ls_handle(buf, got, from);
        else if (buf[0] == 'K' && buf[1] == 'P' && got >= 8) { buf[1] = 'Q'; p2p_send(from, buf, 8, 0); }
    }
}
