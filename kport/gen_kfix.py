"""Generate out/keaton_fixes.py: Keaton's Community Patch fixes (used with her permission), rebuilt as static exe patches.
Source of truth: her dinput8.dll setup code, run against the original exe in a harness (kport/h.c); per-fix result images exe.<Fix>."""
import struct,sys
EXE=open('exe.img','rb').read()
KFIX_VA=0xB00000
FIXES=['Pathfinding','Rotation','EquipmentResistance','CombatBonuses','Frontal',
       'VoiceInterruption','OfficerHealSound','LavaRender','SaveEnumeration','SaveDelete','SaveIntegrity','SaveSlots99']
import transplant
KFX_VA=0xB01000
ROOTS=[0x10003ac0,0x10003b00,0x10003e20,0x10003e90,0x10003b10,0x10002440,0x10002990,0x10002400,0x10001f50,0x100021f0,0x100022a0]
KFX_BLOB,TNEW,TLAZY=transplant.build(ROOTS,KFX_VA)
blob=bytearray(); reloc={}   # dll/stub address -> kfix address
def place(src,data,align=16):
    while len(blob)%align: blob.append(0)
    a=KFIX_VA+len(blob); blob.extend(data); reloc[src]=a; return a
patches=[]
for fx in FIXES:
    A=open('exe.'+fx,'rb').read(); import os; D=open('dll.'+fx if os.path.exists('dll.'+fx) else 'dll.all','rb').read()
    try: V=open('va.'+fx,'rb').read()
    except FileNotFoundError: V=b''
    def remap(t):
        if t in reloc: return reloc[t]
        if t in TNEW: return TNEW[t]                                    # transplanted routine
        if 0x10000000<=t<0x1003d000:
            return place(t,D[t-0x10000000:t-0x10000000+4],4)          # data constant
        if 0x34000000<=t<0x34000000+len(V):
            o=t-0x34000000; n=len(V.rstrip(b'\0'))-o
            return place(t,V[o:o+n])                                    # code stub (position independent)
        return None
    rng=[];s=None
    for i in range(len(EXE)):
        if EXE[i]!=A[i]:
            if s is None or i>e+4:
                if s is not None: rng.append((s,e))
                s=i
            e=i
    if s is not None: rng.append((s,e))
    for s,e in rng:
        new=bytearray(A[s:e+1]); lo=s
        # widen to cover any 4-byte pointer / rel32 overlapping the range
        for p in range(s-4,e+1):
            if p<0: continue
            v=struct.unpack_from('<I',A,p)[0]
            if A[p-1] in (0xE8,0xE9) and p<=e and p+4>s:
                t=(0x400000+p+4+struct.unpack_from('<i',A,p)[0])&0xffffffff
                r=remap(t)
                if r is not None:
                    if p<lo: new=bytearray(A[p:lo])+new; lo=p
                    end=max(lo+len(new),p+4); new=bytearray(A[lo:end])
                    struct.pack_into('<i',new,p-lo,r-(0x400000+p+4)); continue
            if 0x10000000<=v<0x1003d000 or 0x34000000<=v<0x35000000:
                r=remap(v)
                if r is not None:
                    if p<lo: new=bytearray(A[p:lo])+new; lo=p
                    end=max(lo+len(new),p+4); new=bytearray(new[:])+bytearray(A[lo+len(new):end]) if end>lo+len(new) else new
                    struct.pack_into('<I',new,p-lo,r)
        for q in range(len(new)-3):
            v=struct.unpack_from('<I',new,q)[0]
            assert not (0x10000000<=v<0x1003d000 or 0x34000000<=v<0x35000000), (fx,hex(0x400000+lo+q))
        patches.append((fx,0x400000+lo,bytes(EXE[lo:lo+len(new)]),bytes(new)))
with open('../out/keaton_fixes.py','w') as f:
    f.write('# Generated by kport/gen_kfix.py - Keaton (KeatonKuF) Community Patch fixes, used with her permission.\n')
    f.write('KFIX_VA=0x%X\nKFIX_BLOB=bytes.fromhex(%r)\nPATCHES=[\n'%(KFIX_VA,blob.hex()))
    for fx,va,o,n in patches: f.write('  (%r,0x%X,bytes.fromhex(%r),bytes.fromhex(%r)),\n'%(fx,va,o.hex(),n.hex()))
    f.write(']\n')
    f.write('KFX_VA=0x%X\nKFX_BLOB=bytes.fromhex(%r)\n'%(KFX_VA,KFX_BLOB.hex()))
for fx,va,o,n in patches: print(fx,hex(va),len(n))
