"""TEST25: lobby icons for the 6 new team colours (black, white, turquoise, orange, pink, grey), 28x28 like the purple/brown
ones (font_icons.icon), written as DXT5 blocks into net/colicons.inc; eq.c tex_fix places them in free Font2 cells."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from font_icons import icon, dxt5_block
NEW = [('Black', (44, 44, 46)), ('White', (236, 236, 232)), ('Turquoise', (38, 196, 186)),
       ('Orange', (244, 132, 26)), ('Pink', (242, 112, 182)), ('Grey', (128, 128, 130))]
X0, Y0 = 816, 320
out = ['/* generated by scripts/col_icons_gen.py */', '#define NCI %d' % len(NEW), '#define CI_X0 %d' % X0, '#define CI_Y0 %d' % Y0,
       'static const char *const ci_tok[NCI] = { %s };' % ', '.join('"(BfbCol%s)"' % n for n, _ in NEW),
       'static const unsigned char ci_dxt[NCI][49][16] = {']
for n, c in NEW:
    im = icon(c); rows = []
    for by in range(7):
        for bx in range(7):
            pxs = [im.getpixel((bx * 4 + (k & 3), by * 4 + (k >> 2))) for k in range(16)]
            rows.append('{' + ','.join(str(b) for b in dxt5_block(pxs)) + '}')
    out.append(' { ' + ','.join(rows) + ' },')
out.append('};')
open(os.path.join(os.path.dirname(__file__), '..', 'net', 'colicons.inc'), 'w').write('\n'.join(out) + '\n')
print('wrote', len(NEW), 'icons')
